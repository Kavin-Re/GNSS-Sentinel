"""Command-line interface: gen / stream / dashboard / evaluate. Passive analysis only."""
import argparse, json, math, os, sys
import numpy as np
from . import __doc__ as _d  # noqa
from .detectors import DET_ORDER
from .pipeline import Pipeline, load_thresholds, HERE
from .logio import read_log, write_csv, write_nmea
from .dashboard import Recorder, build_html
from . import classifier as clf
from .synth import SCENARIOS, generate


def _open(path):
    return sys.stdin if path == "-" else open(path, "r", newline="")


def run_stream(lines, fmt="auto", thr=None, out=sys.stdout, quiet=False, use_clf=True, rec=None, warm=60):
    pl = Pipeline(thresholds=thr, warm=warm)
    model = None
    if use_clf:
        p = os.path.join(HERE, "default_classifier.json")
        if os.path.exists(p): model, classes = clf.load(p)
    have = dict(clock=False, agc=False, res=False, vel=False, n=0)
    counts = {n: 0 for n in DET_ORDER}; active_s = {n: 0.0 for n in DET_ORDER}; tprev = None; nepoch = 0
    hint_last = None
    if not quiet:
        print("# GNSS-Sentinel: passive analysis. First %d epochs form the baseline and are assumed clean." % warm, file=out)
    reader = read_log(lines, fmt)
    for ep in reader:
        nepoch += 1
        have["clock"] |= math.isfinite(ep.clock_m); have["agc"] |= math.isfinite(ep.agc_db)
        have["res"] |= bool(np.isfinite(ep.res).any()); have["vel"] |= bool(np.isfinite(ep.vel).any())
        scores, raw, events = pl.update(ep)
        if tprev is not None:
            for n, a in pl.active.items():
                if a: active_s[n] += ep.t - tprev
        tprev = ep.t
        if rec is not None: rec.add(ep, scores, events)
        any_active = any(pl.active.values())
        for a in events:
            if a.kind == "start":
                counts[a.detector] += 1
                print("[t=%8.1f s] ALERT   %-10s score %.1f (thr %.1f)  %s" % (a.t, a.detector, a.score, a.thr, a.msg), file=out)
            elif not quiet:
                print("[t=%8.1f s] cleared %-10s" % (a.t, a.detector), file=out)
        if model is not None and any_active and (events or nepoch % 10 == 0):
            wf = pl.window_features()
            if wf is not None:
                pr = clf.proba(model, wf)[0]; k = int(pr.argmax())
                if classes[k] != hint_last:
                    print("[t=%8.1f s]   hint (synthetic-trained classifier, not evidence): %s p=%.2f" % (ep.t, classes[k], pr[k]), file=out)
                    hint_last = classes[k]
        if not any_active: hint_last = None
    reader_bad = getattr(reader, "bad", 0)
    if reader_bad: print("# WARNING: %d malformed NMEA sentence(s) skipped (bad checksum or unparsable fields)" % reader_bad, file=out)
    print("# processed %d epochs; alert episodes: %s" % (nepoch, ", ".join("%s=%d" % (n, counts[n]) for n in DET_ORDER)), file=out)
    na = [n for n, ok in (("clock", have["clock"]), ("cn0_agc AGC/noise terms", have["agc"]), ("raim", have["res"]),
                          ("cusum", have["vel"])) if not ok]
    if na: print("# n/a on this log (field absent): " + ", ".join(na), file=out)
    if nepoch <= warm: print("# WARNING: log shorter than the %d-epoch baseline; no detection was possible" % warm, file=out)
    return counts, active_s, nepoch


def cmd_stream(a):
    thr = load_thresholds(a.thresholds) if a.thresholds else None
    rec = Recorder(thr or load_thresholds()) if a.dashboard else None
    with _open(a.log) as f:
        counts, _, n = run_stream(f, a.format, thr, quiet=a.quiet, use_clf=not a.no_classifier, rec=rec)
    if rec:
        notes = ["Detectors that need fields absent from this log report no scores (flat lines)."]
        with open(a.dashboard, "w") as g: g.write(build_html(rec, os.path.basename(a.log), notes))
        print("# dashboard written to %s" % a.dashboard)
    return 0


def cmd_dashboard(a):
    a.quiet = True
    thr = load_thresholds(a.thresholds) if a.thresholds else load_thresholds()
    rec = Recorder(thr)
    import io
    with _open(a.log) as f: run_stream(f, a.format, thr, out=io.StringIO(), quiet=True, rec=rec)
    with open(a.out, "w") as g: g.write(build_html(rec, os.path.basename(a.log), ["Detectors that need fields absent from this log report no scores (flat lines)."]))
    print("dashboard written to %s (%d epochs, %d alert events)" % (a.out, len(rec.rows), len(rec.alerts)))
    return 0


def cmd_gen(a):
    eps, meta = generate(a.scenario, seed=a.seed, n=a.n, onset=a.onset, profile=a.profile)
    hdr = ("SYNTHETIC TEST DATA generated by GNSS-Sentinel (abstract receiver measurements, not signals).\nmeta: " + json.dumps(meta))
    with open(a.out, "w") as f: write_csv(f, eps, header_comment=hdr)
    if a.nmea:
        with open(a.nmea, "w") as f: write_nmea(f, eps)
    print("wrote %s (%d epochs, scenario=%s, onset=%d)" % (a.out, len(eps), a.scenario, meta["onset"]))
    return 0


def cmd_eval(a):
    from .evaluate import main as ev
    if a.quick: ev(a.out, n_cal=40, n_clean=30, n_att=20, n_train=15, n_shift=10, procs=a.procs, quick=True, write_defaults=False)
    else: ev(a.out, procs=a.procs, write_defaults=a.write_defaults)
    return 0


def main(argv=None):
    ap = argparse.ArgumentParser(prog="gnss_sentinel", description="Passive GNSS interference/spoofing indicator toolkit (simulation-validated only).")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen", help="write a labelled SYNTHETIC test log (CSV, optionally NMEA-like)")
    g.add_argument("scenario", choices=SCENARIOS); g.add_argument("-o", "--out", required=True); g.add_argument("--nmea")
    g.add_argument("--seed", type=int, default=1); g.add_argument("-n", type=int, default=720); g.add_argument("--onset", type=int)
    g.add_argument("--profile", default="nominal", choices=["nominal", "shifted"]); g.set_defaults(fn=cmd_gen)
    s = sub.add_parser("stream", help="read a CSV/NMEA log (file or '-' for stdin) and print alerts with explanations")
    s.add_argument("log"); s.add_argument("--format", choices=["auto", "csv", "nmea"], default="auto")
    s.add_argument("--thresholds"); s.add_argument("--quiet", action="store_true"); s.add_argument("--no-classifier", action="store_true")
    s.add_argument("--dashboard", metavar="OUT.html"); s.set_defaults(fn=cmd_stream)
    d = sub.add_parser("dashboard", help="write an offline single-file HTML dashboard for a log")
    d.add_argument("log"); d.add_argument("-o", "--out", required=True); d.add_argument("--format", choices=["auto", "csv", "nmea"], default="auto")
    d.add_argument("--thresholds"); d.set_defaults(fn=cmd_dashboard)
    e = sub.add_parser("evaluate", help="run the synthetic evaluation (slow: ~15 min)")
    e.add_argument("--out", default="results"); e.add_argument("--quick", action="store_true"); e.add_argument("--procs", type=int, default=2)
    e.add_argument("--write-defaults", action="store_true", help="overwrite packaged thresholds/classifier with this run's")
    e.set_defaults(fn=cmd_eval)
    a = ap.parse_args(argv)
    try:
        return a.fn(a)
    except BrokenPipeError:                 # output piped into head/grep -q that closed early: not an error
        try: sys.stdout = open(os.devnull, "w")
        except OSError: pass
        return 0
    except (OSError, ValueError) as e:      # unreadable file, bad CSV header, ...: one line instead of a traceback
        print("gnss_sentinel: error: %s" % e, file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
